#include <stdio.h>

int main()
{
    int a = 1;
    int b = 2;

    // Demonstração das estruturas condicionais if, else if e else
    if (a < b)
    {
        printf("a é menor que b.\n");
    }
    else if (a == b)
    {
        printf("a é igual a b.\n");
    }
    else
    {
        printf("a é maior que b.\n");
    }

    return 0;
}
